import Link from "next/link";
import type { Metadata } from "next";
import {
  getSandboxDetails,
  listRunsForSandbox,
  listSandboxes,
} from "@/lib/store";
import { EmptyState, Stat, StatusPill } from "@/components/ui";
import {
  ArrowRight,
  ArrowUpRight,
  Check,
  Code,
  Flask,
  Layers,
  Plus,
  Shield,
  Users,
} from "@/components/icons";
import { timeAgo } from "@/lib/utils";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Developer studio",
  description:
    "Publish product sandboxes, model endpoints, and write customer scenarios.",
};

export default function ProviderPage() {
  const sandboxes = listSandboxes();
  const detailed = sandboxes
    .map((sandbox) => {
      const details = getSandboxDetails(sandbox.id);
      if (!details) return null;
      const runs = listRunsForSandbox(sandbox.id, 100);
      return { details, runCount: runs.length, lastRun: runs[0] ?? null };
    })
    .filter((item): item is NonNullable<typeof item> => item !== null);

  const published = detailed.filter(
    (item) => item.details.status === "published"
  ).length;
  const totalRuns = detailed.reduce((sum, item) => sum + item.runCount, 0);
  const totalScenarios = detailed.reduce(
    (sum, item) => sum + item.details.scenarios.length,
    0
  );

  return (
    <div className="mx-auto max-w-7xl px-4 py-12 sm:px-6 lg:px-8">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <p className="font-mono text-[11px] uppercase tracking-[0.2em] text-mint">
            Developer side
          </p>
          <h1 className="mt-3 text-3xl font-semibold tracking-tight text-text sm:text-4xl">
            Developer studio
          </h1>
          <p className="mt-3 max-w-2xl text-sm leading-relaxed text-muted sm:text-base">
            Model your product as a runnable contract, then let customers generate
            their own proof. Publish when the scenarios are honest enough to
            survive a stranger.
          </p>
        </div>
        <Link href="/provider/new" className="btn-primary">
          <Plus className="h-4 w-4" />
          New sandbox
        </Link>
      </div>

      <div className="mt-8 grid grid-cols-2 gap-4 lg:grid-cols-4">
        <Stat
          label="Sandboxes"
          value={detailed.length}
          hint={`${published} published · ${detailed.length - published} drafts`}
          icon={<Flask />}
        />
        <Stat
          label="Scenarios"
          value={totalScenarios}
          hint="Customer journeys modelled"
          icon={<Layers />}
        />
        <Stat
          label="Proof runs"
          value={totalRuns}
          hint="Generated by customers"
          icon={<Shield />}
        />
        <Stat
          label="Live endpoints"
          value={detailed.reduce(
            (sum, item) => sum + item.details.endpoints.length,
            0
          )}
          hint="Across all sandboxes"
          icon={<Code />}
        />
      </div>

      <div className="mt-12">
        <div className="flex items-end justify-between gap-4">
          <div>
            <h2 className="text-xl font-semibold tracking-tight text-text">
              Your sandboxes
            </h2>
            <p className="mt-1 text-sm text-muted">
              Everything here is editable. Drafts stay out of the catalog.
            </p>
          </div>
          <span className="text-xs text-faint">
            {detailed.length} total
          </span>
        </div>

        <div className="mt-5">
          {detailed.length === 0 ? (
            <EmptyState
              title="No sandboxes yet"
              description="Create your first sandbox, add a couple of endpoints and a customer scenario, then publish it."
              action={{ href: "/provider/new", label: "Create a sandbox" }}
            />
          ) : (
            <div className="grid gap-4 md:grid-cols-2">
              {detailed.map(({ details, runCount, lastRun }) => (
                <div key={details.id} className="card p-5">
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex flex-wrap items-center gap-2">
                      <StatusPill status={details.status} />
                      <span className="chip">{details.industry}</span>
                      <span className="chip font-mono">{details.version}</span>
                    </div>
                    <Link
                      href={`/sandbox/${details.slug}`}
                      className="text-faint transition-colors hover:text-mint"
                      aria-label={`View ${details.name}`}
                    >
                      <ArrowUpRight className="h-4 w-4" />
                    </Link>
                  </div>

                  <h3 className="mt-4 text-lg font-semibold tracking-tight text-text">
                    {details.name}
                  </h3>
                  <p className="mt-1.5 line-clamp-2 text-sm text-muted">
                    {details.tagline || "No tagline yet."}
                  </p>

                  <div className="mt-4 flex flex-wrap gap-x-4 gap-y-1 text-[11px] text-faint">
                    <span>{details.endpoints.length} endpoints</span>
                    <span>{details.scenarios.length} scenarios</span>
                    <span>{runCount} runs</span>
                    <span>updated {timeAgo(details.updatedAt)}</span>
                  </div>

                  <div className="mt-4 flex items-center gap-2 border-t border-line pt-4">
                    <Link
                      href={`/provider/${details.id}`}
                      className="btn-ghost flex-1 px-3 py-2 text-xs"
                    >
                      Edit contract
                    </Link>
                    <Link
                      href={`/sandbox/${details.slug}`}
                      className="btn-subtle px-3 py-2 text-xs"
                    >
                      Preview
                    </Link>
                    {lastRun ? (
                      <Link
                        href={`/runs/${lastRun.id}`}
                        className="btn-subtle px-3 py-2 text-xs"
                      >
                        Last proof
                      </Link>
                    ) : null}
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>

      <div className="mt-12 grid gap-4 md:grid-cols-3">
        <div className="card p-5">
          <Users className="h-5 w-5 text-sky" />
          <h3 className="mt-3 text-sm font-semibold text-text">
            Write for a stranger
          </h3>
          <p className="mt-1.5 text-xs leading-relaxed text-muted">
            A good scenario names a persona, states their goal, and asserts only
            what your product actually promises.
          </p>
        </div>
        <div className="card p-5">
          <Shield className="h-5 w-5 text-mint" />
          <h3 className="mt-3 text-sm font-semibold text-text">
            Publish honestly
          </h3>
          <p className="mt-1.5 text-xs leading-relaxed text-muted">
            Leave realistic error rates and latency in place. A sandbox that never
            fails is not a proof — it is a brochure.
          </p>
        </div>
        <div className="card p-5">
          <Check className="h-5 w-5 text-warn" />
          <h3 className="mt-3 text-sm font-semibold text-text">
            Let the report speak
          </h3>
          <p className="mt-1.5 text-xs leading-relaxed text-muted">
            Send customers the report link instead of a demo call. They can run it
            again under their own conditions.
          </p>
        </div>
      </div>

      <div className="mt-10 flex items-center justify-center">
        <Link
          href="/provider/new"
          className="inline-flex items-center gap-2 text-sm text-muted hover:text-mint"
        >
          Add another sandbox
          <ArrowRight className="h-4 w-4" />
        </Link>
      </div>
    </div>
  );
}
